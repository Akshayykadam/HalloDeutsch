// Get module by ID
export const getModuleById = (id: string): CurriculumModule | undefined => {
    return A1_MODULES.find(m => m.id === id);
};

// Get lesson by ID
export const getLessonById = (lessonId: string): CurriculumLesson | undefined => {
    for (const module of A1_MODULES) {
        const lesson = module.lessons.find(l => l.id === lessonId);
        if (lesson) return lesson;
    }
    return undefined;
};

// Get all A1 lessons flat
export const getAllA1Lessons = (): CurriculumLesson[] => {
    return A1_MODULES.flatMap(m => m.lessons);
};

// Calculate total A1 content stats
export const getA1Stats = () => {
    const totalLessons = A1_MODULES.reduce((sum, m) => sum + m.lessons.length, 0);
    const totalHours = A1_MODULES.reduce((sum, m) => sum + m.estimatedHours, 0);
    return {
        modules: A1_MODULES.length,
        lessons: totalLessons,
        estimatedHours: totalHours,
    };
};
