// Helper functions
export const getA2ModuleById = (id: string): CurriculumModule | undefined => {
    return A2_MODULES.find(m => m.id === id);
};

export const getA2LessonById = (lessonId: string): CurriculumLesson | undefined => {
    for (const module of A2_MODULES) {
        const lesson = module.lessons.find(l => l.id === lessonId);
        if (lesson) return lesson;
    }
    return undefined;
};

export const getAllA2Lessons = (): CurriculumLesson[] => {
    return A2_MODULES.flatMap(m => m.lessons);
};

export const getA2Stats = () => {
    const totalLessons = A2_MODULES.reduce((sum, m) => sum + m.lessons.length, 0);
    const totalHours = A2_MODULES.reduce((sum, m) => sum + m.estimatedHours, 0);
    return {
        modules: A2_MODULES.length,
        lessons: totalLessons,
        estimatedHours: totalHours,
    };
};
