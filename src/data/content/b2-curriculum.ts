import { CurriculumModule, CurriculumLesson } from '../../types';

// Helper to create lessons for a module
const createLessons = (moduleId: string, count: number, topic: string): CurriculumLesson[] => {
    return Array.from({ length: count }).map((_, i) => ({
        id: `${moduleId}-l${i + 1}`,
        moduleId: moduleId,
        order: i + 1,
        title: `${topic} Analysis ${i + 1}`,
        titleDe: `${topic} Analyse ${i + 1}`,
        type: i % 2 === 0 ? 'vocabulary' : 'grammar',
        whatLearning: `Advanced analysis of ${topic}`,
        whyLearning: 'B2 level proficiency',
        whereUsed: 'Academic and formal contexts',
        estimatedMinutes: 25,
        vocabularyDomains: ['food', 'household', 'family'],
        grammarTopics: ['b2-konjunktiv1', 'b2-advanced-passive'], // Real B2 grammar topics
        exercises: [],
        masteryThreshold: 80,
        isLocked: i > 0,
        isCompleted: false,
        progress: 0,
    }));
};

