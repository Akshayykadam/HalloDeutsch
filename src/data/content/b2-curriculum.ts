// Helper functions
export const getB2ModuleById = (id: string): CurriculumModule | undefined => {
    return B2_MODULES.find(m => m.id === id);
};

export const getB2LessonById = (lessonId: string): CurriculumLesson | undefined => {
    for (const module of B2_MODULES) {
        const lesson = module.lessons.find(l => l.id === lessonId);
        if (lesson) return lesson;
    }
    return undefined;
};

export const getAllB2Lessons = (): CurriculumLesson[] => {
    return B2_MODULES.flatMap(m => m.lessons);
};

export const getB2Stats = () => {
    const totalLessons = B2_MODULES.reduce((sum, m) => sum + m.lessons.length, 0);
    const totalHours = B2_MODULES.reduce((sum, m) => sum + m.estimatedHours, 0);
    return {
        modules: B2_MODULES.length,
        lessons: totalLessons,
        estimatedHours: totalHours,
    };
};
