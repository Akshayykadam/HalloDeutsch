import { CurriculumModule, CurriculumLesson } from '../../types';

// Helper to create lessons for a module
const createLessons = (moduleId: string, count: number, topic: string): CurriculumLesson[] => {
    return Array.from({ length: count }).map((_, i) => ({
        id: `${moduleId}-l${i + 1}`,
        moduleId: moduleId,
        order: i + 1,
        title: `${topic} Part ${i + 1}`,
        titleDe: `${topic} Teil ${i + 1}`,
        type: i % 2 === 0 ? 'vocabulary' : 'grammar',
        whatLearning: `Deep dive into ${topic}`,
        whyLearning: 'B1 level requirement',
        whereUsed: 'Work and social life',
        estimatedMinutes: 20,
        vocabularyDomains: ['general'],
        exercises: [],
        masteryThreshold: 80,
        isLocked: i > 0,
        isCompleted: false,
        progress: 0,
    }));
};

