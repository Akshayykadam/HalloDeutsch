// Helper functions
export const getB1ModuleById = (id: string): CurriculumModule | undefined => {
    return B1_MODULES.find(m => m.id === id);
};

export const getB1LessonById = (lessonId: string): CurriculumLesson | undefined => {
    for (const module of B1_MODULES) {
        const lesson = module.lessons.find(l => l.id === lessonId);
        if (lesson) return lesson;
    }
    return undefined;
};

export const getAllB1Lessons = (): CurriculumLesson[] => {
    return B1_MODULES.flatMap(m => m.lessons);
};

export const getB1Stats = () => {
    const totalLessons = B1_MODULES.reduce((sum, m) => sum + m.lessons.length, 0);
    const totalHours = B1_MODULES.reduce((sum, m) => sum + m.estimatedHours, 0);
    return {
        modules: B1_MODULES.length,
        lessons: totalLessons,
        estimatedHours: totalHours,
    };
};
